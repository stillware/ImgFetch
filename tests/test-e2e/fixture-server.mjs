function lazyrowsHtml() {
  // loading="lazy" images far down the page; the stability wait must let
  // them decode before each tile is captured.
  let body = '';
  for (let i = 0; i < 10; i += 1) {
    const [r, g, b] = rowColor(i + 200);
    const hex = [r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('');
    body += `<div style="height:1900px"></div><img loading="lazy" data-li="${i}" src="/img/300/200/${hex}.png" width="300" height="200" style="display:block;margin:0 auto">\n`;
  }
  return `<!DOCTYPE html><html><head><title>lazyrows</title></head><body style="margin:0">${body}</body></html>`;
}
