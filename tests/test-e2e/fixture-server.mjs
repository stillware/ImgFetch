// --- minimal CRC32 + PNG writer (pure Node) ---
const CRC_T = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) c = CRC_T[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function pngChunk(type, data) {
  const td = Buffer.from(type, 'ascii');
  const b = Buffer.alloc(12 + data.length);
  b.writeUInt32BE(data.length, 0);
  td.copy(b, 4);
  data.copy(b, 8);
  b.writeUInt32BE(crc32(Buffer.concat([td, data])), 8 + data.length);
  return b;
}
export function makePng(w, h, [r, g, b]) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; ihdr[9] = 2; // 8-bit truecolor
  const stride = w * 3 + 1;
  const raw = Buffer.alloc(stride * h);
  for (let y = 0; y < h; y += 1) {
    raw[y * stride] = 0;
    for (let x = 0; x < w; x += 1) {
      const o = y * stride + 1 + x * 3;
      // Slight vertical gradient so bands/tiles are detectable.
      const f = 0.7 + (0.3 * (y % 256)) / 256;
      raw[o] = Math.min(255, r * f) | 0;
      raw[o + 1] = Math.min(255, g * f) | 0;
      raw[o + 2] = Math.min(255, b * f) | 0;
    }
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', zlib.deflateSync(raw)),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}
function colorFor(i) {
  const palette = [[220, 60, 60], [60, 160, 220], [70, 180, 90], [230, 180, 50], [150, 90, 200]];
  return palette[i % palette.length];
}

